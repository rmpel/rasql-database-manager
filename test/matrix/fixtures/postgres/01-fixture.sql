-- ---------------------------------------------------------------------------
-- parents / children: foreign keys, composite and expression indexes, generated column
-- ---------------------------------------------------------------------------
CREATE TABLE parents (
  id serial PRIMARY KEY,
  name varchar(50) NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE parents IS 'Referenced by children';

CREATE TABLE children (
  id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  parent_id integer NOT NULL,
  label varchar(50) NOT NULL DEFAULT 'none',
  position integer NOT NULL DEFAULT 0,
  score numeric(5, 2) DEFAULT '-1.5',
  full_label text GENERATED ALWAYS AS (label || ' #' || position) STORED,
  CONSTRAINT fk_children_parent FOREIGN KEY (parent_id) REFERENCES parents (id)
    ON UPDATE RESTRICT ON DELETE CASCADE,
  CONSTRAINT uq_parent_position UNIQUE (parent_id, position)
);
COMMENT ON TABLE children IS 'Has a foreign key to parents';
COMMENT ON COLUMN children.label IS 'Shown in lists';
CREATE INDEX idx_parent_label ON children (parent_id, label DESC);
CREATE INDEX idx_lower_label ON children (lower(label)) WHERE position > 0;

